public class Product
{
     int p_id;
     String p_name;
     String p_company;
     int p_price;
     String dom;
     int p_quantity;
     public Product(int p_id,String p_name,String p_company,int p_price,String dom,int p_quantity)
     {
         this.p_id=p_id;
         this.p_name=p_name;
         this.p_company=p_company;
         this.p_price=p_price;
         this.dom=dom;
         this.p_quantity=p_quantity;
     }
}
